def search_by_concept(
    query: str,
    doc_id: str | None = None,
    top_k: int = 5,
) -> list[tuple[SourceSection, float]]:
    """Concept route: search sections by keyword matching.

    This is the lexical fallback when LLM/embedding is not available.
    Scores sections by keyword overlap with the query.

    Args:
        query: Search query.
        doc_id: Optional document ID to restrict search.
        top_k: Maximum number of results.

    Returns:
        List of (section, score) tuples, sorted by score descending.
    """
    results: list[tuple[SourceSection, float]] = []
    query_terms = set(query.lower().split())

    doc_ids = [doc_id] if doc_id else [d.doc_id for d in list_okf_documents()]

    for did in doc_ids:
        loaded = load_okf_document(did)
        if loaded is None:
            continue
        _, sections, _ = loaded

        for section in sections:
            content_lower = section.content.lower()
            title_lower = section.title.lower()
            text = title_lower + " " + content_lower

            # Simple TF scoring
            score = sum(1 for term in query_terms if term in text)
            if score > 0:
                # Normalize by content length
                score = score / (len(text) / 1000 + 1)
                results.append((section, score))

    results.sort(key=lambda x: x[1], reverse=True)
    return results[:top_k]


def search_by_bucket(
    query: str,
    doc_id: str | None = None,
    top_k: int = 5,
) -> list[tuple[SourceSection, float]]:
    """Bucket route: match query to buckets, then retrieve sections.

    If buckets exist for a document, match the query against bucket
    titles/summaries/keys, then return the sections in matching buckets.

    Args:
        query: Search query.
        doc_id: Optional document ID to restrict search.
        top_k: Maximum number of results.

    Returns:
        List of (section, score) tuples.
    """
    results: list[tuple[SourceSection, float]] = []
    query_lower = query.lower()

    doc_ids = [doc_id] if doc_id else [d.doc_id for d in list_okf_documents()]

    for did in doc_ids:
        loaded = load_okf_document(did)
        if loaded is None:
            continue
        _, sections, buckets = loaded

        if not buckets:
            # No buckets — fall back to concept search
            continue

        # Build section lookup
        section_map = {s.section_id: s for s in sections}

        # Match query against buckets
        for bucket in buckets:
            bucket_text = (bucket.title + " " + bucket.summary + " " + bucket.bucket_key).lower()
            bucket_terms = set(bucket_text.split())
            query_terms = set(query_lower.split())
            overlap = query_terms & bucket_terms

            if overlap:
                score = len(overlap) / (len(query_terms) + 1)
                for sid in bucket.section_ids:
                    section = section_map.get(sid)
                    if section:
                        results.append((section, score))

    results.sort(key=lambda x: x[1], reverse=True)
    return results[:top_k]


def dual_route_search(
    query: str,
    doc_id: str | None = None,
    top_k: int = 5,
) -> list[dict[str, Any]]:
    """Dual-route retrieval: try bucket route first, then concept route.

    Merges and deduplicates results from both routes.

    Args:
        query: Search query.
        doc_id: Optional document ID to restrict search.
        top_k: Maximum number of results.

    Returns:
        List of result dicts with section_id, doc_id, title, content,
        score, and route fields.
    """
    # Try bucket route first
    bucket_results = search_by_bucket(query, doc_id, top_k)

    # Then concept route
    concept_results = search_by_concept(query, doc_id, top_k)

    # Merge and deduplicate
    seen: set[str] = set()
    merged: list[dict[str, Any]] = []

    for section, score in bucket_results:
        if section.section_id not in seen:
            seen.add(section.section_id)
            merged.append({
                "section_id": section.section_id,
                "doc_id": section.doc_id,
                "title": section.title,
                "content": section.content[:500],  # Truncate for preview
                "score": score,
                "route": "bucket",
            })

    for section, score in concept_results:
        if section.section_id not in seen:
            seen.add(section.section_id)
            merged.append({
                "section_id": section.section_id,
                "doc_id": section.doc_id,
                "title": section.title,
                "content": section.content[:500],
                "score": score * 0.8,  # Slightly lower priority for concept route
                "route": "concept",
            })

    merged.sort(key=lambda x: x["score"], reverse=True)
    return merged[:top_k]


# ---------------------------------------------------------------------------
# Bucket generation (LLM-powered, optional)
# ---------------------------------------------------------------------------

async def generate_buckets(
    doc: SourceDocument,
    sections: list[SourceSection],
    agent_id: str | None = None,
) -> list[Bucket]:
    """Generate cross-section task buckets using LLM.

    This is the OKF enhancement that groups sections by query intent.
    Uses model_factory to call the LLM with a bucketing prompt.

    Args:
        doc: The source document.
        sections: The document's sections.
        agent_id: Agent ID for model configuration.

    Returns:
        List of generated Bucket objects.
    """
    if not sections:
        return []

    try:
        from ..agents.model_factory import create_model_and_formatter
        from ..framework.message import Msg, TextBlock
        from ..utils.model_response import consume_model_response
    except ImportError as e:
        logger.warning("Cannot import model dependencies for bucket generation: %s", e)
        return []

    # Build section summaries for the prompt
    section_summaries = []
    for s in sections[:MAX_SECTIONS_PER_DOC]:
        preview = s.content[:200].replace("\n", " ")
        section_summaries.append(f"  - [{s.section_id}] {s.title}: {preview}")

    prompt = f"""\
Analyze the following document sections and create 3-8 task buckets that group
sections by the types of queries they can answer.

Document: {doc.title}
Sections:
{chr(10).join(section_summaries)}

Output a JSON array of bucket objects:
```json
[
  {{
    "bucket_key": "short_identifier",
    "title": "Human-readable title",
    "summary": "What queries this bucket answers",
    "section_ids": ["{sections[0].section_id if sections else ''}"],
    "applicable_query_types": ["factual", "procedural", "legal_basis"]
  }}
]
```

Rules:
1. Each section can appear in multiple buckets.
2. bucket_key should be lowercase with underscores.
3. applicable_query_types: factual, procedural, legal_basis, definitional, analytical
4. Output ONLY the JSON array, no explanation.
"""

    try:
        model, _ = create_model_and_formatter(agent_id=agent_id)
        messages = [
            Msg(
                name="system",
                role="system",
                content=[TextBlock(type="text", text="You generate JSON output for knowledge bucketing.")],
            ),
            Msg(
                name="user",
                role="user",
                content=[TextBlock(type="text", text=prompt)],
            ),
        ]
        raw = await consume_model_response(model, messages)

        # Parse JSON array
        import re
        match = re.search(r"\[.*\]", raw, re.DOTALL)
        if not match:
            logger.warning("No JSON array found in bucket generation response")
            return []

        bucket_data = json.loads(match.group(0))
        buckets = []
        for i, b in enumerate(bucket_data):
            buckets.append(Bucket(
                bucket_id=f"{doc.doc_id}_b{i}",
                doc_id=doc.doc_id,
                bucket_key=b.get("bucket_key", f"bucket_{i}"),
                title=b.get("title", ""),
                summary=b.get("summary", ""),
                section_ids=b.get("section_ids", []),
                applicable_query_types=b.get("applicable_query_types", []),
            ))

        # Update sections with bucket references
        for bucket in buckets:
            for sid in bucket.section_ids:
                for section in sections:
                    if section.section_id == sid:
                        if bucket.bucket_id not in section.bucket_ids:
                            section.bucket_ids.append(bucket.bucket_id)

        logger.info("Generated %d buckets for document '%s'", len(buckets), doc.doc_id)
        return buckets

    except Exception as e:
        logger.error("Bucket generation failed: %s", e)
        return []


# ---------------------------------------------------------------------------
# Citation formatting (simplified from StaffDeck's citations.py)
# ---------------------------------------------------------------------------

def format_citations(results: list[dict[str, Any]]) -> list[dict[str, str]]:
    """Format search results as citation objects.

    Args:
        results: Output from dual_route_search().

    Returns:
        List of citation dicts with label, doc_id, section_id, and preview.
    """
    citations = []
    for i, result in enumerate(results):
        label = f"[{i+1}]"
        if result.get("title"):
            label += f" {result['title']}"
        citations.append({
            "label": label,
            "doc_id": result.get("doc_id", ""),
            "section_id": result.get("section_id", ""),
            "preview": result.get("content", "")[:200],
            "route": result.get("route", ""),
        })
    return citations
